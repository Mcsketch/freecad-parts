"""Write CATALOG.md from every part's embedded Label / Comment. Plain Python, no FreeCAD:

    python3 tools/catalog.py [library-root]
"""
import os
import re
import sys
import zipfile

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def info(path):
    with zipfile.ZipFile(path) as z:
        xml = z.read("Document.xml").decode("utf-8", "replace")
    g = lambda name: (re.findall(r'<Property name="%s"[^>]*>\s*<String value="([^"]*)"' % name, xml) or [""])[-1]
    return g("Label") or os.path.basename(path)[:-6], g("Comment").replace("&quot;", '"').replace("&amp;", "&")


rows = {}
for d, dirs, files in os.walk(ROOT):
    dirs[:] = sorted(x for x in dirs if not x.startswith(".") and x not in ("tools", "thumbs"))
    for f in sorted(files):
        if f.lower().endswith(".fcstd"):
            rows.setdefault(os.path.relpath(d, ROOT).replace(os.sep, "/"), []).append((f[:-6], *info(os.path.join(d, f))))

out = ["# Catalog", "", "Generated by `tools/catalog.py` — do not edit. %d parts." % sum(map(len, rows.values())), ""]
for folder in sorted(rows):
    out += ["## %s" % folder, "", "| File | Part | Notes |", "|---|---|---|"]
    for name, label, comment in rows[folder]:
        thumb = "thumbs/%s/%s.png" % (folder, name)
        cell = "![](%s) `%s`" % (thumb, name) if os.path.exists(os.path.join(ROOT, thumb)) else "`%s`" % name
        out.append("| %s | %s | %s |" % (cell, label, comment.replace("|", "\\|")))
    out.append("")
open(os.path.join(ROOT, "CATALOG.md"), "w", encoding="utf-8").write("\n".join(out))
print("CATALOG.md: %d parts" % sum(map(len, rows.values())))
